"""navera_lite/tools/adopt.py — fly YOUR stack: replace the course's finished parts in this folder by the ones you
wrote in your earlier lesson folders, each one only if the course's tests still pass with it. Part of NAVERA Lite,
the course's teaching stack (mission 33). Written for the course; it is not NAVERA code.

    python3 -m navera_lite.tools.adopt                 what would be adopted (nothing is changed)
    python3 -m navera_lite.tools.adopt --apply         adopt them, then run the whole suite and one flight
    python3 -m navera_lite.tools.adopt --apply --only geo,arbiter      only these parts

Where your parts are: every lesson folder next to this one (../NN-name/) has a navera_lite/PARTS.md that says which
parts you wrote there ("✏️ YOUR TODOs"). For each part the LAST mission where you wrote it counts.
A part is adopted when: it has no TODO left; it defines every public name of the course's version (a part written in
an early mission may lack a function a later mission added); and its own course test (tests/test_<part>.py, when
there is one) passes with it. With --apply the whole suite and one simulated flight must pass too, else nothing is
changed. The list of adopted parts is written to navera_lite/MINE.md: commit it with the parts.
"""
import ast
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

# @part 33
STUB_MARKS = ("# TODO: write your code " + "above", "NotImplementedError(" + '"TODO')
# @part 33
ROW = re.compile(r"^\|\s*`([a-z_/]+\.py)`\s*\|\s*(\d+)\s*\|\s*✏️")


# @part 33
def your_parts(lessons_dir, here):
    """part path (e.g. "geo.py", "ros/gps_node.py") → (mission number, the file in your lesson folder) for the parts
    you wrote yourself: the rows marked ✏️ in the PARTS.md of every other lesson folder; the latest mission wins."""
    found = {}
    for md in sorted(glob.glob(os.path.join(lessons_dir, "[0-9][0-9]-*", "navera_lite", "PARTS.md"))):
        folder = os.path.dirname(os.path.dirname(md))
        if os.path.realpath(folder) == os.path.realpath(here):
            continue
        nn = int(os.path.basename(folder)[:2])
        with open(md, encoding="utf-8") as f:
            for line in f:
                m = ROW.match(line)
                if m and (m.group(1) not in found or found[m.group(1)][0] < nn):
                    found[m.group(1)] = (nn, os.path.join(folder, "navera_lite", m.group(1)))
    return found


# @part 33
def public_names(text):
    """The public top-level names (functions, classes, CONSTANTS) a Python source defines."""
    names = set()
    for node in ast.parse(text).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
    return {n for n in names if not n.startswith("_")}


# @part 33
def body(text):
    """A source without its first comment line (the 'generated for mission NN' header differs between copies)."""
    lines = text.splitlines()
    return "\n".join(lines[1:] if lines and lines[0].startswith("# generated by") else lines)


# @part 33
def pytest(root, *targets, timeout=300):
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    keep = [p for p in env.get("PYTHONPATH", "").split(os.pathsep) if p.startswith("/opt/ros/")]
    env["PYTHONPATH"] = os.pathsep.join([root] + keep)
    r = subprocess.run([sys.executable, "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider", *targets], cwd=root,
                       env=env, capture_output=True, text=True, timeout=timeout)
    lines = [ln for ln in (r.stdout + r.stderr).strip().splitlines() if ln.strip()]
    return r.returncode, (lines[-1] if lines else "")


# @part 33
def scratch_copy(here):
    d = tempfile.mkdtemp(prefix="adopt_")
    shutil.copytree(os.path.join(here, "navera_lite"), os.path.join(d, "navera_lite"),
                    ignore=shutil.ignore_patterns("__pycache__"))
    for f in ("navera_lite.yaml", "pytest.ini"):
        if os.path.exists(os.path.join(here, f)):
            shutil.copy(os.path.join(here, f), d)
    return d


# @part 33
def judge_part(here, rel, nn, src):
    """(adopt?, why) for one of your parts, tested in a scratch copy of this folder's stack."""
    ours = os.path.join(here, "navera_lite", rel)
    if not os.path.exists(src):
        return False, "not found"
    if not os.path.exists(ours):
        return False, "not a part of this stack"
    with open(src, encoding="utf-8") as f:
        mine = f.read()
    with open(ours, encoding="utf-8") as f:
        course = f.read()
    if body(mine) == body(course):
        return False, "already the same text as the course's"
    if any(m in mine for m in STUB_MARKS):
        return False, "a TODO is left in it"
    try:
        missing = sorted(public_names(course) - public_names(mine))
    except SyntaxError as e:
        return False, f"syntax error line {e.lineno}"
    if missing:
        return False, "lacks " + ", ".join(missing[:4]) + (" …" if len(missing) > 4 else "") + " (added after mission " \
            f"{nn:02d})"
    test = os.path.join("navera_lite", "tests", "test_" + os.path.basename(rel))
    d = scratch_copy(here)
    try:
        shutil.copy(src, os.path.join(d, "navera_lite", rel))
        if os.path.exists(os.path.join(d, test)):
            code, last = pytest(d, test)
            if code:
                return False, f"its course test fails: {last}"
            return True, f"{os.path.basename(test)}: {last}"
        mod = "navera_lite." + rel[:-3].replace("/", ".")
        r = subprocess.run([sys.executable, "-B", "-c", f"import {mod}"], cwd=d, capture_output=True, text=True,
                           env=dict(os.environ, PYTHONPATH=d))
        if r.returncode:
            return False, "it does not import: " + (r.stderr.strip().splitlines() or ["?"])[-1]
        return True, "no course test of its own: checked by the whole suite and the flight (--apply)"
    finally:
        shutil.rmtree(d, ignore_errors=True)


# @part 33
def fly_once(root):
    """One short simulated flight with the stack of root (campaign/jam.json): (ok, last line)."""
    sc = os.path.join(os.getcwd(), "campaign", "jam.json")
    if not os.path.exists(sc):
        return True, "no campaign/jam.json here: flight skipped"
    out = tempfile.mkdtemp(prefix="adopt_fly_")
    env = dict(os.environ, PYTHONPATH=root, PYTHONDONTWRITEBYTECODE="1")
    r = subprocess.run([sys.executable, "-B", "-m", "navera_lite.sim.run", sc, "--out", out, "--quiet"], cwd=root,
                       env=env, capture_output=True, text=True, timeout=300)
    shutil.rmtree(out, ignore_errors=True)
    lines = [ln for ln in (r.stdout + r.stderr).strip().splitlines() if ln.strip()]
    return r.returncode == 0, (lines[-1] if lines else "")


# @part 33
def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    here = os.getcwd()
    if not os.path.isdir(os.path.join(here, "navera_lite")):
        sys.exit("run it from your lesson folder (the one that holds navera_lite/)")
    only = None
    if "--only" in args:
        i = args.index("--only")
        only = {p.strip() for p in (args[i + 1] if i + 1 < len(args) else "").split(",") if p.strip()}
        if not only:
            sys.exit("--only needs part names, like --only geo,arbiter")
    found = your_parts(os.path.dirname(here), here)
    if not found:
        sys.exit("no earlier lesson folder with parts of yours was found next to this one (../NN-name/navera_lite/)")
    good = []
    print(f"{'part':22s} {'from':>6s}  result")
    for rel, (nn, src) in sorted(found.items(), key=lambda x: (x[1][0], x[0])):
        name = rel[:-3].replace("/", ".")
        if only is not None and name not in only and rel not in only:
            continue
        ok, why = judge_part(here, rel, nn, src)
        verdict = "✔ adopt — " if ok else "· keep the course's — "
        print(f"{rel:22s} {nn:6d}  {verdict}{why}")
        if ok:
            good.append((rel, nn, src))
    if "--apply" not in args:
        print(f"\n{len(good)} part(s) of yours can replace the course's. Nothing was changed: add --apply to adopt them.")
        return 0
    if not good:
        print("\nnothing to adopt")
        return 0
    d = scratch_copy(here)
    try:
        for rel, _, src in good:
            shutil.copy(src, os.path.join(d, "navera_lite", rel))
        code, last = pytest(d, "navera_lite/tests")
        print(f"\nthe whole suite with your parts: {last}")
        fl_ok, fl_last = fly_once(d)
        print(f"one flight (campaign/jam.json): {fl_last}")
        if code or not fl_ok:
            print("✘ nothing adopted: with all of them together the stack does not pass. Try fewer parts with "
                  "--only (start with one), or fix the part in its own lesson folder.")
            return 1
    finally:
        shutil.rmtree(d, ignore_errors=True)
    for rel, _, src in good:
        shutil.copy(src, os.path.join(here, "navera_lite", rel))
    with open(os.path.join(here, "navera_lite", "MINE.md"), "w", encoding="utf-8") as f:
        f.write("# Your parts in this stack\n\nAdopted by `python3 -m navera_lite.tools.adopt --apply` (the course's "
                "tests and one flight passed with them):\n\n| Part | From your mission |\n|---|---|\n")
        for rel, nn, _ in good:
            f.write(f"| `{rel}` | {nn:02d} |\n")
    print(f"✔ adopted {len(good)} part(s); navera_lite/MINE.md lists them. Commit them: "
          "git add navera_lite && git commit -m \"use my own parts\"")
    return 0


if __name__ == "__main__":
    sys.exit(main())
