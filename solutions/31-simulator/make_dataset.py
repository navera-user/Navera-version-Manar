#!/usr/bin/env python3
"""Mission 31 dataset (teacher only — never copy this file into datasets/: students read everything there).

    PYTHONPATH= python3 solutions/31-simulator/make_dataset.py [corridor] [stream]     # both by default, ≈ 3 min

Writes datasets/31-simulator/ (students: /data/academy/31-simulator/):
  corridor/corridor.json    the corridor's frame: centre lat/lon, extent (east/north metres), metres per pixel of
                            each picture, the route (start/destination in east/north metres), © OSM
  corridor/day_ortho.png    grey, north-up, 0.5 m/px, 1000 m × 3800 m: an aerial-style drawing (render_view's 'pseudo'
                            style, rendered directly in Web-Mercator boxes so the chunks join exactly). The simulated
                            day camera resamples its photos from it; the map patch the matcher searches is the same
                            picture at 1.0 m/px (as in mission 22: photo and map come from one orthophoto).
  corridor/night_ref.png    grey, 8 × the zoom-17 pixel (≈ 7.75 m/px, mission 25's scale): the day reference
  corridor/night_temp.png   the same ground as a night 'temperature' picture (mission 25's material model)
  gps_input.bin             the bytes an autopilot received during a 60 s flight of the course's reference stack
                            (GPS_INPUT frames + 3 HEARTBEATs), with injected faults: 2 corrupted bytes, line noise,
                            4 lost frames, 1 doubled frame, a cut last frame. Generated by navera_lite.output (the
                            course's own encoder) — no NAVERA output.
  README.md                 neutral description + © OpenStreetMap contributors
and courses/31-simulator/hidden/stream_truth.json (check only): what gps_input.bin contains (counts, flags, a few
decoded values), recomputed from the generator's own record of what it wrote.

The corridor lies west of Sousse (Tunisia), lat ≈ 35.805–35.840, lon ≈ 10.542–10.554: fields, a motorway and the edge
of a town. It is inside a TEST cell of mission 25's split (never used for night training) and outside missions 23's
TileNet training area. Mission 21's random patch places may overlap it: this is a behaviour test, not an accuracy test.
"""
import json
import math
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.realpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "datasets", "31-simulator")
HIDDEN = os.path.join(REPO, "courses", "31-simulator", "hidden")
sys.path.insert(0, os.path.join(REPO, "datasets", "_map"))
sys.path.insert(0, os.path.join(REPO, "solutions", "_navera_lite"))

ATTRIBUTION = "© OpenStreetMap contributors (ODbL), https://www.openstreetmap.org/copyright"
LAT0, LON0 = 35.8225, 10.5480          # the corridor's centre
HALF_E, HALF_N = 500.0, 1900.0         # half-width (east) and half-length (north), metres
DAY_MPP = 0.5
CHUNK = 1000                           # px per rendered chunk (+ PAD each side, cropped)
PAD = 24


def night_mpp(lat):
    """8 × the zoom-17 map pixel (mission 25's scale, ≈ 7.75 m at Sousse)."""
    return 8 * 40075016.686 * math.cos(math.radians(lat)) / 2 ** 17 / 256


def render_ortho(mpp, shadows=True):
    """The corridor north-up at mpp m/px, BGR: pixel centre (x, y) ↔ east = (x + 0.5)·mpp − HALF_E,
    north = HALF_N − (y + 0.5)·mpp, metres from the centre (render_view's local metres, Mercator-scaled)."""
    import render_view as rv
    keep = rv.SUN_SHADOW
    if not shadows:
        rv.SUN_SHADOW = (0.0, 0.0)
    try:
        W, H = int(round(2 * HALF_E / mpp)), int(round(2 * HALF_N / mpp))
        mx0, my0 = rv.latlon_to_merc(LAT0, LON0)
        k = 1.0 / math.cos(math.radians(LAT0))
        out = np.zeros((H, W, 3), np.uint8)
        for y0 in range(0, H, CHUNK):
            for x0 in range(0, W, CHUNK):
                x1, y1 = min(W, x0 + CHUNK), min(H, y0 + CHUNK)
                a0, b0, a1, b1 = x0 - PAD, y0 - PAD, x1 + PAD, y1 + PAD
                box = (mx0 + (a0 * mpp - HALF_E) * k, my0 + (HALF_N - b1 * mpp) * k,
                       mx0 + (a1 * mpp - HALF_E) * k, my0 + (HALF_N - b0 * mpp) * k)
                img = rv._pseudo(box, a1 - a0, b1 - b0, mpp)
                out[y0:y1, x0:x1] = img[PAD:PAD + (y1 - y0), PAD:PAD + (x1 - x0)]
                print(f"  chunk {x0},{y0} done", flush=True)
        return out
    finally:
        rv.SUN_SHADOW = keep


def corridor():
    d = os.path.join(OUT, "corridor")
    os.makedirs(d, exist_ok=True)
    print("day ortho (0.5 m/px)…", flush=True)
    day = render_ortho(DAY_MPP)
    cv2.imwrite(os.path.join(d, "day_ortho.png"), cv2.cvtColor(day, cv2.COLOR_BGR2GRAY), [cv2.IMWRITE_PNG_COMPRESSION, 9])
    nm = night_mpp(LAT0)
    print(f"night reference and temperature ({nm:.3f} m/px, rendered 4 × finer)…", flush=True)
    sys.path.insert(0, os.path.join(REPO, "solutions", "25-thermal-night"))
    import make_dataset as m25                                     # mission 25's material model (teacher code)
    fine_ref = render_ortho(nm / 4.0, shadows=True)
    fine_nos = render_ortho(nm / 4.0, shadows=False)
    W, H = int(round(2 * HALF_E / nm)), int(round(2 * HALF_N / nm))
    ref = cv2.cvtColor(cv2.resize(fine_ref, (W, H), interpolation=cv2.INTER_AREA), cv2.COLOR_BGR2GRAY)
    temp = m25.to_u8(m25.temperature(fine_nos, "night"), W, H)
    cv2.imwrite(os.path.join(d, "night_ref.png"), ref)
    cv2.imwrite(os.path.join(d, "night_temp.png"), temp)
    meta = {"centre_lat": LAT0, "centre_lon": LON0, "half_east_m": HALF_E, "half_north_m": HALF_N,
            "day_m_per_px": DAY_MPP, "night_m_per_px": round(2 * HALF_E / W, 6),
            "pixels": "pixel centre (x, y) ↔ east = (x + 0.5)·m_per_px − half_east_m, "
                      "north = half_north_m − (y + 0.5)·m_per_px (metres from the centre)",
            "route": {"start_en": [0.0, -1600.0], "dest_en": [0.0, 1600.0]},
            "attribution": ATTRIBUTION}
    with open(os.path.join(d, "corridor.json"), "w") as f:
        json.dump(meta, f, indent=1)
    cv2.imwrite(os.path.join(os.environ.get("PREVIEW_DIR", "/tmp"), "corridor_preview.jpg"), cv2.resize(day, (W * 2, H * 2), interpolation=cv2.INTER_AREA))


# ------------------------------------------------------------------------------------------- the byte stream
def stream():
    """gps_input.bin: 60 s of a reference flight (GPS good, then jammed at 30 s → day vision, σ 15 m stated), every
    frame the messenger sent, then damaged on purpose. Returns the truth dict (also written to hidden/)."""
    from navera_lite import output as O
    from navera_lite.sim import run as R
    sc = {"name": "stream", "vehicle": "drone", "vision": "target", "seed": 31, "duration_s": 60.0,
          "faults": [[30.0, "gps", "jammed"]]}
    world = R.fly(sc, mine=False, quiet=True, keep_frames=True)
    frames = world.sent_frames                                   # list of bytes, in order
    rng = np.random.default_rng(3131)
    hb = bytes([O.STX, 9, 0, 0, 0, 1, 191, 0, 0, 0]) + bytes([0, 0, 0, 0, 18, 8, 0, 0, 3])
    hb = hb + O.frame_crc(hb + b"\0\0", 0).to_bytes(2, "little")
    n = len(frames)
    lost = sorted(rng.choice(np.arange(20, n - 20), 4, replace=False).tolist())
    doubled = int(rng.integers(20, n - 20))
    while doubled in lost or doubled + 1 in lost:
        doubled += 1
    corrupt = sorted(rng.choice([i for i in range(20, n - 20) if i not in lost and i != doubled], 2,
                                replace=False).tolist())
    out = bytearray(b"\x00\x13\xfd\x07")                         # line noise, including a lone STX
    sent_seqs, good, kinds = [], 0, []
    for i, f in enumerate(frames):
        if i in (0, n // 2, n - 5):
            out += hb
            sent_seqs.append(None)
        if i in lost:
            continue
        g = bytearray(f)
        if i in corrupt:
            g[14] ^= 0x40                                          # one bit flipped in the payload
        out += g
        kinds.append("bad" if i in corrupt else "ok")
        if i == doubled:
            out += g
            kinds.append("ok")
        if i == n // 3:
            out += bytes([0x55, 0xAA, 0x00])                         # noise between two frames
    cut = frames[-1][:9]
    out += cut                                                       # a frame cut by the end of the recording
    with open(os.path.join(OUT, "gps_input.bin"), "wb") as fh:
        fh.write(bytes(out))
    parsed = O.parse_frames(bytes(out))
    gps = [p for p in parsed if p["msgid"] == O.GPS_INPUT_ID and p["crc_ok"]]
    dec = [O.decode_gps_input(p["payload"]) for p in gps]
    truth = {"frames": len(parsed), "gps_ok": len(gps), "bad_crc": sum(p["crc_ok"] is False for p in parsed),
             "heartbeats": sum(p["msgid"] == 0 for p in parsed),
             "lost_doubled": list(O.lost_frames([p["seq"] for p in gps])),
             "fix3": sum(d["fix_type"] == 3 for d in dec), "nofix": sum(d["fix_type"] == 1 for d in dec),
             "flag_counts": {}, "shortest_payload": min(len(p["payload"]) for p in gps),
             "max_horiz_accuracy": max(d["horiz_accuracy"] for d in dec),
             "first_vision_lat": next(d["lat"] for d in dec if d["satellites_visible"] == 0 and d["fix_type"] == 3)}
    for d in dec:
        truth["flag_counts"][str(d["ignore_flags"])] = truth["flag_counts"].get(str(d["ignore_flags"]), 0) + 1
    os.makedirs(HIDDEN, exist_ok=True)
    with open(os.path.join(HIDDEN, "stream_truth.json"), "w") as fh:
        json.dump(truth, fh, indent=1)
    print("gps_input.bin:", len(out), "bytes;", truth)
    return truth


README = """# Mission 31 data (read only)

| File | What |
|---|---|
| `corridor/corridor.json` | the test corridor west of Sousse (Tunisia): its centre, its size, the metres per pixel of each picture, how a pixel maps to east/north metres, and the route the simulator flies |
| `corridor/day_ortho.png` | the corridor north-up, grey, 0.5 m per pixel (1000 m × 3800 m): an aerial-style drawing rendered from OpenStreetMap data. The simulated day camera takes its photos from it |
| `corridor/night_ref.png`, `corridor/night_temp.png` | the same ground at about 7.75 m per pixel: a day reference and a night "temperature" picture (mission 25's kind), aligned pixel for pixel |
| `gps_input.bin` | the bytes an autopilot received on its serial port during one simulated flight of NAVERA Lite: MAVLink 2 frames, as received |

The pictures are drawings made from OpenStreetMap data (not photographs, not real thermal images).
Pixels: (x, y) = (column, row), the centre of the top-left pixel is (0, 0).

Map data © OpenStreetMap contributors (ODbL 1.0), https://www.openstreetmap.org/copyright.
The renders are a produced work of that data.
"""


def main():
    steps = sys.argv[1:] or ["corridor", "stream"]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write(README)
    if "corridor" in steps:
        corridor()
    if "stream" in steps:
        stream()


if __name__ == "__main__":
    main()
