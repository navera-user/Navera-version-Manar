#!/usr/bin/env python3
"""make_dataset.py — TEACHER ONLY. Writes datasets/29-arbiter/ (the lab's scenarios and the reference run of
the race) with the course's reference judge (solutions/29-arbiter/navera_lite, generated by lite_build).

    python3 solutions/29-arbiter/make_dataset.py          (from the academy root, ROS sourced)

Deterministic (no randomness). Outputs:
    race.csv               31 s: GPS good, day vision, GPS lost, GPS back at σ 40 m, GPS "no fix", a 5 km jump,
                           night vision with no stated σ, a celestial fix stamped 60 s ahead, then nothing
    revival.csv            GPS good, ONE GPS fix stamped 20 s ahead, then GPS dead; day vision all along
    lockout.csv            the same future fix, but the honest GPS goes on
    flapping.csv           a GPS that comes and goes every 0.5–1.5 s for 30 s, day vision all along
    reference_run.json     the reference judge on race.csv: decisions at 11 moments and the switch instants
    README.md              neutral description
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ACADEMY = os.path.realpath(os.path.join(HERE, "..", ".."))
FILES = os.path.join(ACADEMY, "courses", "29-arbiter", "files")
OUT = os.path.join(ACADEMY, "datasets", "29-arbiter")

os.chdir(HERE)                                     # navera_lite/ = the complete reference copy
sys.path.insert(0, HERE)
sys.path.insert(1, FILES)                          # judge_lab.py, runner_kit.py
from navera_lite.geo import offset                 # noqa: E402
import judge_lab                                   # noqa: E402

START = (35.8245, 10.6346)          # NAVERA's test area, Sousse (Tunisia)
HEADER = "t_s,source,lat,lon,a,b,c,cov_type,valid,delay_s"


def pos(t, speed=15.0, e0=0.0, n0=0.0):
    """The vehicle flies east at `speed` m/s from START; plus an offset (e0, n0) m."""
    return offset(START[0], START[1], speed * t + e0, n0)


def row(t, src, latlon, sigma=None, valid=1, delay=0.0, ctype=None):
    lat, lon = latlon
    if sigma is None:
        a = c = 0.0
        ct = 0 if ctype is None else ctype
    else:
        a = c = float(sigma) ** 2
        ct = 1 if ctype is None else ctype
    if lat != lat:
        return f"{t:.2f},{src},nan,nan,{a:g},0,{c:g},{ct},{valid},{delay:g}"
    return f"{t:.2f},{src},{lat:.7f},{lon:.7f},{a:g},0,{c:g},{ct},{valid},{delay:g}"


def race():
    r = []
    for k in range(15):                                       # GPS good 1.0 … 8.0 s, every 0.5 s, σ 3 m
        t = 1.0 + 0.5 * k
        r.append((t, row(t, "gps", pos(t), 3.0)))
    for k in range(20):                                       # day vision 3 … 22 s, σ 30 m, photo 0.8 s old
        t = 3.0 + k
        r.append((t + 0.3, row(t + 0.3, "day", pos(t - 0.5, e0=12.0, n0=-8.0), 30.0, delay=0.8)))
    for k in range(7):                                        # GPS back 14 … 17 s at HDOP 20: σ 40 m
        t = 14.0 + 0.5 * k
        r.append((t, row(t, "gps", pos(t), 40.0)))
    for k in range(5):                                        # GPS "no fix" 17.5 … 19.5 s
        t = 17.5 + 0.5 * k
        r.append((t, row(t, "gps", (float("nan"), float("nan")), None, valid=0)))
    r.append((20.0, row(20.0, "gps", pos(20.0, e0=5000.0), 3.0)))           # a 5 km jump
    for t in (23.0, 24.0):                                    # night vision: no stated σ (type 0)
        r.append((t, row(t, "night", pos(t - 1.0, e0=-20.0, n0=15.0), None, delay=1.0)))
    r.append((25.0, row(25.0, "celestial", pos(25.0, e0=900.0, n0=-600.0), 2000.0, delay=-60.0)))
    return [x for _, x in sorted(r, key=lambda p: p[0])]


SAMPLES = [(0.5, "nothing published yet"), (2.0, "GPS only"), (5.0, "GPS and day vision"),
           (9.5, "GPS silent for 1.5 s"), (12.0, "GPS silent for 4 s"), (15.0, "GPS back for 1 s, σ 40 m"),
           (16.5, "GPS back for 2.5 s, σ 40 m"), (18.5, "GPS says: no fix"), (21.0, "GPS jumped 5 km"),
           (27.0, "day vision silent, night vision"), (30.5, "everything old or refused")]
END_S = 31.0


def revival():
    r = []
    for k in range(9):                                        # GPS 1 … 9 s, 20 m/s
        t = 1.0 + k
        r.append((t, row(t, "gps", pos(t, speed=20.0), 3.0)))
    r.append((10.0, row(10.0, "gps", pos(10.0, speed=20.0), 3.0, delay=-20.0)))   # stamped 20 s ahead
    for k in range(39):                                       # day vision 2 … 40 s
        t = 2.0 + k
        r.append((t + 0.4, row(t + 0.4, "day", pos(t - 0.4, speed=20.0, e0=10.0, n0=6.0), 30.0, delay=0.8)))
    return [x for _, x in sorted(r, key=lambda p: p[0])]


def lockout():
    r = []
    for k in range(40):                                       # honest GPS 1 … 40 s, 20 m/s
        t = 1.0 + k
        r.append((t, row(t, "gps", pos(t, speed=20.0), 3.0)))
    r.append((10.5, row(10.5, "gps", pos(10.5, speed=20.0), 3.0, delay=-20.0)))   # one fix stamped 20 s ahead
    for k in range(39):
        t = 2.0 + k
        r.append((t + 0.4, row(t + 0.4, "day", pos(t - 0.4, speed=20.0, e0=10.0, n0=6.0), 30.0, delay=0.8)))
    return [x for _, x in sorted(r, key=lambda p: p[0])]


FLAPS = [(0.0, 1), (2.5, 0), (3.5, 1), (4.5, 0), (5.0, 1), (6.5, 0), (7.0, 1), (8.0, 0), (9.5, 1), (10.5, 0),
         (11.0, 1), (13.0, 0), (13.5, 1), (14.0, 0), (15.0, 1), (16.5, 0), (17.0, 1), (18.0, 0), (18.5, 1),
         (20.0, 0), (21.0, 1), (22.0, 0), (22.5, 1), (25.0, 0), (25.5, 1), (26.5, 0), (27.5, 1)]


def flapping():
    r = []
    for k in range(60):                                       # GPS every 0.5 s, 0.5 … 30 s
        t = 0.5 + 0.5 * k
        on = [v for t0, v in FLAPS if t0 <= t][-1]
        if on:
            r.append((t, row(t, "gps", pos(t), 3.0)))
        else:
            r.append((t, row(t, "gps", (float("nan"), float("nan")), None, valid=0)))
    for k in range(30):
        t = 1.0 + k
        r.append((t + 0.25, row(t + 0.25, "day", pos(t - 0.55, e0=40.0, n0=-25.0), 30.0, delay=0.8)))
    return [x for _, x in sorted(r, key=lambda p: p[0])]


def write_csv(name, lines):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(HEADER + "\n" + "\n".join(lines) + "\n")
    return path


def reference_run(path):
    rows = judge_lab._rows(path)
    c = dict(judge_lab.settings.DEFAULTS)
    judge = judge_lab.arb_mod.Arbiter(c)
    run = judge_lab.simulate(judge, rows, END_S)
    samples = []
    for t, what in SAMPLES:
        d = [d for tt, d, _ in run if tt <= t + 1e-9][-1]
        samples.append({"t_s": t, "what": what, "state": d.state, "source": d.source, "reason": d.reason})
    switches = [{"t_s": round(t - judge_lab.CLOCK0, 3), "from": a, "to": b} for t, a, b in judge.switches]
    return {"scenario": "race.csv", "judge": "the course's reference judge (simulated clock, ticks at 5 Hz)",
            "samples": samples, "switches": switches}


README = """# Mission 29 — scenarios for the judge

Scenario files in the replay format of mission 12 (`t_s,source,lat,lon,a,b,c,cov_type,valid,delay_s`):
`race.csv` (31 s, every source), `revival.csv`, `lockout.csv`, `flapping.csv`.
`reference_run.json`: what the course's reference judge decided on `race.csv` (simulated clock, 5 Hz ticks):
the state, source and reason at 11 moments, and the instants where the winner changed.
Positions are in NAVERA's test area, Sousse (Tunisia); every number is synthetic.
"""


def main():
    os.makedirs(OUT, exist_ok=True)
    race_path = write_csv("race.csv", race())
    write_csv("revival.csv", revival())
    write_csv("lockout.csv", lockout())
    write_csv("flapping.csv", flapping())
    ref = reference_run(race_path)
    with open(os.path.join(OUT, "reference_run.json"), "w") as f:
        json.dump(ref, f, indent=1, ensure_ascii=False)
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write(README)
    for s in ref["samples"]:
        print(f"{s['t_s']:5.1f}  {s['state']:8s} {s['source'] or '-':9s} {s['reason']}")
    print(ref["switches"])


if __name__ == "__main__":
    main()
