# ---------------------------------------------------------------- real frames
def pixelate(img, block):
    import cv2
    h, w = img.shape[:2]
    small = cv2.resize(img, (max(1, w // block), max(1, h // block)), interpolation=cv2.INTER_AREA)
    return cv2.resize(small, (w, h), interpolation=cv2.INTER_NEAREST)


def make_frames():
    import cv2
    os.makedirs(os.path.join(OUT, "frames"), exist_ok=True)
    for i in range(N):
        img = cv2.imread(os.path.join(SRC, "frames", f"f{FIRST + i:04d}.jpg"))
        assert img is not None and img.shape == (1080, 1920, 3)
        img[540:] = pixelate(img[540:], BLOCK)
        cv2.imwrite(os.path.join(OUT, "frames", f"frame_{i:03d}.jpg"), img, [cv2.IMWRITE_JPEG_QUALITY, 85])
    shutil.copyfile(os.path.join(SRC, "insta360_top.yaml"), os.path.join(OUT, "insta360_top.yaml"))


# ---------------------------------------------------------------- quaternions (w, x, y, z)
def q_mul(a, b):
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    return np.array([w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2,
                     w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
                     w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2,
                     w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2])


def q_axis(axis, ang):
    v = np.zeros(3)
    v["xyz".index(axis)] = 1.0
    return np.concatenate([[math.cos(ang / 2)], math.sin(ang / 2) * v])


def q_ypr(yaw, pitch, roll):
    """ZYX (aerospace) yaw, pitch, roll in radians -> (w, x, y, z)."""
    return q_mul(q_mul(q_axis("z", yaw), q_axis("y", pitch)), q_axis("x", roll))


# ---------------------------------------------------------------- the turn flight
def smooth(u):
    u = min(max(u, 0.0), 1.0)
    return 0.5 - 0.5 * math.cos(math.pi * u)


def roll_deg(t):
    if t < 4.0:
        return 0.0
    if t < 5.5:
        return 25.0 * smooth((t - 4.0) / 1.5)
    if t < 15.0:
        return 25.0
    if t < 16.5:
        return 25.0 * (1.0 - smooth((t - 15.0) / 1.5))
    return 0.0


def pitch_deg(t):
    return 2.0 + 3.0 * math.sin(2 * math.pi * 0.4 * t)


DT_FINE = 0.0005
FINE_T = np.arange(0.0, 26.0, DT_FINE)
V, G = 15.0, 9.81
_yaw_rate = np.array([G * math.tan(math.radians(roll_deg(t))) / V for t in FINE_T])
FINE_YAW = math.radians(40.0) + np.concatenate([[0.0], np.cumsum(0.5 * (_yaw_rate[1:] + _yaw_rate[:-1]) * DT_FINE)])


def true_q(t):
    yaw = float(np.interp(t, FINE_T, FINE_YAW))
    return q_ypr(yaw, math.radians(pitch_deg(t)), math.radians(roll_deg(t)))


def make_turn(rng):
    imu = []
    t = 0.0
    while t < 25.0:
        ts = t + rng.gauss(0.0, 0.001)
        if not (17.0 <= ts < 17.8):                              # IMU dropout
            q = true_q(ts)
            # 0.02 deg (1 sigma) of random rotation noise
            axis = np.array([rng.gauss(0, 1) for _ in range(3)])
            axis /= np.linalg.norm(axis)
            ang = math.radians(rng.gauss(0.0, 0.02))
            q = q_mul(q, np.concatenate([[math.cos(ang / 2)], math.sin(ang / 2) * axis]))
            if q[0] < 0:
                q = -q
            imu.append((ts, q / np.linalg.norm(q)))
        t += 0.02
    imu.sort(key=lambda r: r[0])
    with open(os.path.join(OUT, "turn_imu.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["t_s", "qw", "qx", "qy", "qz"])
        for ts, q in imu:
            w.writerow([f"{EPOCH + ts:.6f}"] + [f"{c:.12f}" for c in q])
    with open(os.path.join(OUT, "turn_frames.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["frame", "grab_time_s", "true_qw", "true_qx", "true_qy", "true_qz"])
        k, t = 0, 1.0
        while t < 24.0:
            grab = t + rng.gauss(0.0, 0.002)
            q = true_q(grab - 0.138)
            w.writerow([k, f"{EPOCH + grab:.6f}"] + [f"{c:.12f}" for c in q])
            k += 1
            t += T


# ---------------------------------------------------------------- timing logs
def make_grab_log(rng):
    times = []
    for k in range(int(60.0 / T)):
        t = 5.0 + k * T + rng.gauss(0.0, 0.0012)
        if rng.random() < 0.03:
            t += rng.uniform(0.004, 0.012)                       # USB / scheduler hiccup
        times.append(t)
    drop = set(rng.sample(range(50, len(times) - 50), 6))
    stall = 5.0 + 41.2
    times = [t for k, t in enumerate(times) if k not in drop and not (stall <= t < stall + 0.3)]
    times.sort()
    with open(os.path.join(OUT, "grab_log.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["grab_time_s"])
        for t in times:
            w.writerow([f"{EPOCH + t:.6f}"])


def make_flashes(rng):
    SCREEN, LAT, EXPO = 0.020, 0.105, 0.010
    BLACK, WHITE = 30.0, 200.0
    flashes, white_spans = [], []
    t = 3.0
    for i in range(20):
        t += 0.7                                                 # black for 0.7 s
        t0 = t + rng.uniform(0.0, 0.01)                          # program turns the screen white
        flashes.append(t0)
        white_spans.append((t0 + SCREEN, t0 + 0.7 + SCREEN))
        t = t0 + 0.7
    end = t + 0.7
    phase = rng.uniform(0.0, T)
    rows = []
    k = 0
    while True:
        mid = 2.0 + phase + k * T
        if mid > end:
            break
        a, b = mid - EXPO / 2, mid + EXPO / 2
        lit = sum(max(0.0, min(b, e) - max(a, s)) for s, e in white_spans) / EXPO
        bright = BLACK + (WHITE - BLACK) * lit + rng.gauss(0.0, 3.0)
        rows.append((mid + LAT + rng.gauss(0.0, 0.001), bright))
        k += 1
    with open(os.path.join(OUT, "flashes.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["flash", "t_white_s"])
        for i, t0 in enumerate(flashes):
            w.writerow([i, f"{EPOCH + t0:.6f}"])
    with open(os.path.join(OUT, "flash_frames.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["grab_time_s", "brightness"])
        for g, br in rows:
            w.writerow([f"{EPOCH + g:.6f}", f"{br:.1f}"])


def make_replay_times(rng):
    with open(os.path.join(OUT, "grab_times.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["frame", "grab_time_s"])
        for i in range(N):
            w.writerow([f"frame_{i:03d}.jpg", f"{EPOCH - 40000 + i * T + rng.gauss(0, 0.002):.4f}"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--timing", action="store_true", help="only the synthetic timing files")
    a = ap.parse_args()
    if not a.timing:
        make_frames()
    make_replay_times(random.Random(19))
    make_grab_log(random.Random(1919))
    make_flashes(random.Random(190))
    make_turn(random.Random(1990))
    with open(os.path.join(OUT, "README.txt"), "w") as f:
        f.write(README)
    print("done:", OUT)


if __name__ == "__main__":
    main()
