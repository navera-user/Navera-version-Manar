#!/usr/bin/env python3
"""lite_build.py — generate each mission's NAVERA Lite starter and solution from the one reference.

    tools/lite_build.py 06-coordinates     # one mission
    tools/lite_build.py --all              # every mission that has a manifest fragment
    tools/lite_build.py --parts            # print part → introducing mission (from the @part tags)
    tools/lite_build.py 99-demo --ref DIR --out DIR   # a reference and an output root elsewhere (tests)

Design: reviews/fledgling-design.md §1.5–1.6 (read Fledgling as NAVERA Lite, §7).

SOURCE (teacher only, never mounted): solutions/_navera_lite/
    manifest.json             global settings only: {"package", "version", "settings_file"}
    manifest.d/<id>.json      ONE FILE PER MISSION (missions are built in parallel: no shared list):
                              {"parts": ["geo", "ros.convert"], "todo_missions": [6],
                               "tests": ["test_geo.py"], "extra": []}
                              parts: modules the mission needs (the import closure is added and printed);
                              "*" = every part. todo_missions: normally [NN]. tests: files of
                              navera_lite/tests/ to ship. extra: more paths under the reference root,
                              copied as they are (e.g. "navera_lite/sim/_lite").
    navera_lite/<part>.py     the complete reference. Every top-level def/class carries a tag line
                              right above it (above its decorators):
                                  # @part 29 todo 4     introduced in 29, a TODO there (TODO 4)
                                  # @part 12            introduced in 12, given (never a TODO)
                              Any other top-level statement (constant, import) may carry a tag too:
                              untagged ones are always kept. A method may carry its own tag; untagged
                              methods follow their class (a class tagged "todo K" stubs them all).
    navera_lite/__init__.py   hand-written once, no per-part data: PARTS is generated into every copy
    navera_lite/tests/        test_<part>.py
    navera_lite.yaml          the settings (ROS 2 params-file format), shipped with every copy

OUTPUT for mission NN (both folders are generated: never edit them by hand):
    courses/<id>/files/navera_lite/   tags < NN finished; tags == NN with a todo: signature + docstring +
                                      stub; tags > NN removed; __init__.py with PARTS; PARTS.md
    courses/<id>/files/navera_lite.yaml   (only if absent: it is the student's file once shipped)
    solutions/<id>/navera_lite/       the same parts, complete
    A stub is `return None   # TODO: write your code above, and return the result`, or
    `raise NotImplementedError("TODO K")` for a function that returns nothing.

VERIFIED after writing (any failure: exit 1): every TODO docstring has an `Example:`; the starter
imports; its TODO functions are stubs; the shipped tests pass on the solution (pytest); lite_lint is
clean on both generated trees.
"""
import argparse
import ast
import json
import os
import re
import shutil
import subprocess
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ACADEMY = os.path.realpath(os.path.join(TOOLS, ".."))
sys.path.insert(0, TOOLS)
import lite_lint  # noqa: E402

REF = os.path.join(ACADEMY, "solutions", "_navera_lite")
TAG = re.compile(r"^\s*# @part (\d{2})(?: todo (\d+))?\s*$")
LOOKS_LIKE_TAG = re.compile(r"^\s*#\s*@part\b")
STUB_RETURN = "return None   # TODO: write your code above, and return the result"
GENERATED = "# generated by tools/lite_build.py for mission {nn} — authors: edit solutions/_navera_lite, not this copy"
MARKER = "generated by tools/lite_build.py"
RULE = 96                                      # width of the "# TODO K ----" banner (mission 01 style)


class BuildError(Exception):
    pass


# ------------------------------------------------------------------ manifests
def load_manifests(ref):
    """(global settings, {mission id: fragment}) — one fragment file per mission."""
    g = {"package": "navera_lite", "version": "course-2026.1", "settings_file": "navera_lite.yaml"}
    p = os.path.join(ref, "manifest.json")
    if os.path.exists(p):
        g.update(json.load(open(p)))
    frags = {}
    d = os.path.join(ref, "manifest.d")
    if os.path.isdir(d):
        for fn in sorted(os.listdir(d)):
            if fn.endswith(".json"):
                lid = fn[:-5]
                if not re.match(r"^\d{2}-", lid):
                    raise BuildError(f"manifest.d/{fn}: the name must be <NN-slug>.json")
                fr = json.load(open(os.path.join(d, fn)))
                unknown = set(fr) - {"parts", "todo_missions", "tests", "extra", "note"}
                if unknown:
                    raise BuildError(f"manifest.d/{fn}: unknown keys {sorted(unknown)}")
                fr.setdefault("parts", [])
                fr.setdefault("todo_missions", [int(lid[:2])])
                fr.setdefault("tests", [])
                fr.setdefault("extra", [])
                frags[lid] = fr
    return g, frags


def _mod(part):
    """'ros/convert.py' | 'ros.convert' → 'ros.convert'."""
    p = part[:-3] if part.endswith(".py") else part
    return p.replace("/", ".").strip(".")


def _modpath(ref, pkg, mod):
    return os.path.join(ref, pkg, *mod.split(".")) + ".py"


def all_parts(ref, pkg):
    out = []
    root = os.path.join(ref, pkg)
    for dp, dns, fns in os.walk(root):
        dns[:] = sorted(d for d in dns if d not in ("tests", "__pycache__"))
        for fn in sorted(fns):
            if fn.endswith(".py") and fn != "__init__.py":
                out.append(_mod(os.path.relpath(os.path.join(dp, fn), root)))
    return out


# ------------------------------------------------------------------ tags
def _tag_above(lines, node):
    """(mission, todo) from the tag line right above the node (above its decorators), else None."""
    first = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
    if first >= 2:
        m = TAG.match(lines[first - 2])
        if m:
            return first - 1, int(m.group(1)), (int(m.group(2)) if m.group(2) else None)
    return None


def _returns_value(fn):
    """Does the function return something (a `return x` of its own, not of a nested function)?"""
    stack = list(fn.body)
    while stack:
        n = stack.pop()
        if isinstance(n, ast.Return) and n.value is not None and not (
                isinstance(n.value, ast.Constant) and n.value.value is None):
            return True
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
            continue
        stack.extend(ast.iter_child_nodes(n))
    return False


def _docstring_node(fn):
    b = fn.body[0] if fn.body else None
    if isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant) and isinstance(b.value.value, str):
        return b
    return None


def parse_part(path):
    """Read a reference part: (lines, items). items: dicts with node, tag line, mission, todo, kind,
    parent class (methods)."""
    src = open(path).read()
    lines = src.split("\n")
    try:
        tree = ast.parse(src, path)
    except SyntaxError as e:
        raise BuildError(f"{path}:{e.lineno}: syntax error in the reference: {e.msg}")
    items, used_tags = [], set()
    rel = os.path.relpath(path)
    for i, l in enumerate(lines, 1):
        if LOOKS_LIKE_TAG.match(l) and not TAG.match(l):
            raise BuildError(f"{rel}:{i}: misspelt tag {l.strip()!r}: write `# @part NN` or `# @part NN todo K`")
    for node in tree.body:
        if isinstance(node, ast.Expr) and node is tree.body[0]:
            continue                                         # module docstring
        t = _tag_above(lines, node)
        isdef = isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))
        if t is None:
            if isdef:
                raise BuildError(f"{rel}:{node.lineno}: `{node.name}` has no `# @part NN` tag line above it")
            continue
        used_tags.add(t[0])
        if t[2] is not None and not isdef:
            raise BuildError(f"{rel}:{t[0]}: only a function, a class or a method can be a TODO")
        it = {"node": node, "tag": t[0], "mission": t[1], "todo": t[2], "parent": None,
              "kind": "class" if isinstance(node, ast.ClassDef) else ("def" if isdef else "stmt")}
        items.append(it)
        if isinstance(node, ast.ClassDef):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    st = _tag_above(lines, sub)
                    if st:
                        used_tags.add(st[0])
                        if st[1] < t[1]:
                            raise BuildError(f"{rel}:{st[0]}: method tagged {st[1]:02d} inside a class of {t[1]:02d}")
                        items.append({"node": sub, "tag": st[0], "mission": st[1], "todo": st[2],
                                      "parent": it, "kind": "def"})
                    elif t[2] is not None:                    # a TODO class: its methods are TODOs
                        items.append({"node": sub, "tag": None, "mission": t[1], "todo": t[2],
                                      "parent": it, "kind": "def"})
    for i, l in enumerate(lines, 1):
        if LOOKS_LIKE_TAG.match(l) and i not in used_tags:
            raise BuildError(f"{rel}:{i}: this @part tag is not right above a top-level statement or a method")
    return lines, items


def check_examples(ref, pkg):
    """Every TODO function's docstring has an Example: (with its result)."""
    errs = []
    for mod in all_parts(ref, pkg):
        path = _modpath(ref, pkg, mod)
        _, items = parse_part(path)
        for it in items:
            if it["todo"] is None or it["kind"] == "class" or it["kind"] == "stmt":
                continue
            d = _docstring_node(it["node"])
            if d is None or not re.search(r"\bExamples?:", d.value.value):
                errs.append(f"{os.path.relpath(path)}:{it['node'].lineno}: TODO `{it['node'].name}` needs a "
                            "docstring with an `Example:` (a call and its result)")
    if errs:
        raise BuildError("\n".join(errs))


def parts_table(ref, pkg):
    """part → the mission that introduces it (the smallest @part tag of the module)."""
    out = {}
    for mod in all_parts(ref, pkg):
        _, items = parse_part(_modpath(ref, pkg, mod))
        ms = [it["mission"] for it in items]
        if ms:
            out[mod] = min(ms)
    return out


# ------------------------------------------------------------------ generating one part
def _indent(line):
    return line[:len(line) - len(line.lstrip())]


def _banner(ind, k):
    head = f"{ind}# TODO {k} "
    return head + "-" * max(4, RULE - len(head))


def _marker(ind, it, nn, todo_missions, has_todo=False):
    m, k = it["mission"], it["todo"]
    if k is not None and m == nn and m in todo_missions:
        return _banner(ind, k)
    if has_todo:                                     # a given class holding this mission's TODO methods
        return f"{ind}# {'from mission %02d' % m if m < nn else 'given'} — this class is finished except its TODO methods"
    if m < nn:
        return f"{ind}# from mission {m:02d} — finished: read it, use it, do not change it"
    return f"{ind}# given — read it and use it, no need to change it"


def render(path, nn, todo_missions, stub):
    """The text of one part for mission nn (stub=False: the solution). Returns (text, todo names,
    names of the functions stubbed)."""
    lines, items = parse_part(path)
    edits = []                         # (first line, last line, replacement lines) 1-based inclusive
    stubbed = []
    removed_classes = set()
    todo_classes = {id(it["parent"]) for it in items if it["parent"] is not None and it["todo"] is not None
                    and it["mission"] == nn and nn in todo_missions}
    for it in items:
        node = it["node"]
        ind = _indent(lines[node.lineno - 1])
        if it["parent"] is not None and id(it["parent"]) in removed_classes:
            continue
        first = it["tag"] or min([node.lineno] + [d.lineno for d in node.decorator_list])
        if it["mission"] > nn:                                   # a later mission: cut out
            last = node.end_lineno
            while last < len(lines) and lines[last].strip() == "":
                last += 1                                        # with the blank lines after it
            edits.append((first, last, []))
            if it["kind"] == "class":
                removed_classes.add(id(it))
            continue
        if it["tag"]:
            edits.append((it["tag"], it["tag"], [] if it["kind"] == "stmt" else [_marker(ind, it, nn, todo_missions, id(it) in todo_classes)]))
        is_todo = it["todo"] is not None and it["mission"] == nn and nn in todo_missions
        if is_todo and stub and it["kind"] == "def":
            d = _docstring_node(node)
            body_ind = _indent(lines[node.body[0].lineno - 1])
            start = d.end_lineno + 1 if d else node.body[0].lineno
            stmt = STUB_RETURN if _returns_value(node) else f'raise NotImplementedError("TODO {it["todo"]}")'
            edits.append((start, node.end_lineno, [body_ind + stmt]))
            stubbed.append(node.name)
    for it in items:                   # a class whose whole body was cut keeps a `pass`
        if it["kind"] == "class" and id(it) not in removed_classes:
            node = it["node"]
            cuts = sorted(e for e in edits if e[2] == [] and node.lineno < e[0] <= node.end_lineno)
            if cuts and all(any(e[0] <= s.lineno <= e[1] for e in cuts) for s in node.body):
                f0, l0, _ = cuts[0]
                edits[edits.index(cuts[0])] = (f0, l0, [_indent(lines[node.body[0].lineno - 1]) + "pass", ""])
    out = list(lines)
    for first, last, repl in sorted(edits, key=lambda e: -e[0]):
        out[first - 1:last] = repl
    text = "\n".join(out)
    text = re.sub(r"\n{4,}", "\n\n\n", text).rstrip("\n") + "\n"
    mine = {}                                     # in TODO order (PARTS.md lists them as the lab does)
    for it in items:
        if it["todo"] is not None and it["mission"] == nn and nn in todo_missions and it["kind"] == "def":
            mine.setdefault(_qualname(it), int(it["todo"]))
    todos = sorted(mine, key=lambda q: (mine[q], q))
    return text, todos, stubbed


def imports_of(text, pkg):
    """navera_lite modules a generated text imports (absolute imports only, as the style requires)."""
    out = set()
    for n in ast.walk(ast.parse(text)):
        if isinstance(n, ast.ImportFrom) and n.module and (n.module == pkg or n.module.startswith(pkg + ".")):
            sub = n.module[len(pkg) + 1:]
            if sub:
                out.add(sub)
            else:
                out.update(a.name for a in n.names)
        elif isinstance(n, ast.Import):
            for a in n.names:
                if a.name.startswith(pkg + "."):
                    out.add(a.name[len(pkg) + 1:])
    return out


# ------------------------------------------------------------------ building one mission
def _clear(path):
    """Remove a generated folder (refuse one that does not look generated)."""
    if not os.path.exists(path):
        return
    init = os.path.join(path, "__init__.py")
    if not (os.path.exists(init) and MARKER in open(init).read()):
        raise BuildError(f"{path} exists and was not made by lite_build: move it away first")
    shutil.rmtree(path)


def _write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def _init_text(g, nn, parts_here, intro, header):
    pk = g["package"]
    body = ", ".join(f'"{m}": {intro.get(m, nn)}' for m in sorted(parts_here))
    return (f'{header}\n"""{pk} — NAVERA Lite, the navigation stack you build in this course (this copy: mission {nn:02d}).\n\n'
            f"Written for the course; it is not NAVERA code. PARTS lists the parts this copy holds and the\n"
            f'mission that introduces each one (PARTS.md says which ones you write here)."""\n'
            f'__version__ = "{g["version"]}"\n\nPARTS = {{{body}}}\n')


def _qualname(it):
    """`func` for a module function, `Class.method` for a method: a given method may share a TODO's name."""
    return (it["parent"]["node"].name + "." if it["parent"] is not None else "") + it["node"].name


def _defs_by_qualname(tree):
    """{"func": [node], "Class.method": [node]} for the module's functions and its classes' methods."""
    defs = {}
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
            defs.setdefault(n.name, []).append(n)
        elif isinstance(n, ast.ClassDef):
            for sub in n.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    defs.setdefault(f"{n.name}.{sub.name}", []).append(sub)
    return defs


def _parts_md(nn, parts_here, intro, todos_by_part):
    rows = ["# NAVERA Lite — the parts in this folder", "",
            f"Mission {nn:02d}. Finished parts come from the course's reference: read them, use them.", "",
            "| Part | Mission | Status |", "|---|---|---|"]
    for m in sorted(parts_here, key=lambda m: (intro.get(m, nn), m)):
        t = todos_by_part.get(m) or []
        st = f"✏️ YOUR TODOs: {', '.join(t)}" if t else ("given" if intro.get(m, nn) == nn else "finished")
        rows.append(f"| `{m.replace('.', '/')}.py` | {intro.get(m, nn):02d} | {st} |")
    return "\n".join(rows) + "\n"


def build(lid, ref=REF, out_root=ACADEMY, verify=True, quiet=False):
    say = (lambda *a: None) if quiet else print
    g, frags = load_manifests(ref)
    if lid not in frags:
        raise BuildError(f"no manifest fragment {os.path.join(ref, 'manifest.d', lid + '.json')}")
    fr, nn, pkg = frags[lid], int(lid[:2]), g["package"]
    check_examples(ref, pkg)
    intro = parts_table(ref, pkg)
    known = set(all_parts(ref, pkg))
    want = known if "*" in fr["parts"] else {_mod(p) for p in fr["parts"]}
    for m in want:
        if m not in known:
            raise BuildError(f"manifest.d/{lid}.json: part {m} has no file {_modpath(ref, pkg, m)}")
    todo_missions = [int(x) for x in fr["todo_missions"]]
    # closure on the generated texts (a removed later function does not pull its imports in)
    sol, stub, todos_by_part, stubs_by_part = {}, {}, {}, {}
    queue, added = sorted(want), []
    while queue:
        m = queue.pop()
        if m in sol:
            continue
        path = _modpath(ref, pkg, m)
        sol[m], todos, _ = render(path, nn, todo_missions, stub=False)
        stub[m], _, stubbed = render(path, nn, todo_missions, stub=True)
        todos_by_part[m], stubs_by_part[m] = todos, stubbed
        for dep in imports_of(sol[m], pkg) | imports_of(stub[m], pkg):
            if dep not in known:
                if os.path.isdir(os.path.join(ref, pkg, *dep.split("."))):
                    continue                                   # a sub-package's __init__
                raise BuildError(f"{pkg}/{m.replace('.', '/')}.py imports {pkg}.{dep}, which is not a part")
            if dep not in sol and dep not in queue:
                queue.append(dep)
                if dep not in want:
                    added.append(dep)
    if added:
        say(f"  closure adds: {', '.join(sorted(added))}")
    header = GENERATED.format(nn=f"{nn:02d}")
    starter_dir = os.path.join(out_root, "courses", lid, "files", pkg)
    solution_dir = os.path.join(out_root, "solutions", lid, pkg)
    for d, texts in ((starter_dir, stub), (solution_dir, sol)):
        _clear(d)
        _write(os.path.join(d, "__init__.py"), _init_text(g, nn, texts, intro, header))
        for m, t in texts.items():
            _write(os.path.join(d, *m.split(".")) + ".py", header + "\n" + t)
            for k in range(1, len(m.split("."))):                # sub-package __init__.py
                sub = m.split(".")[:k]
                ip = os.path.join(d, *sub, "__init__.py")
                if not os.path.exists(ip):
                    src = os.path.join(ref, pkg, *sub, "__init__.py")
                    _write(ip, header + "\n" + (open(src).read() if os.path.exists(src) else ""))
        for tf in fr["tests"]:
            src = os.path.join(ref, pkg, "tests", tf)
            if not os.path.exists(src):
                raise BuildError(f"manifest.d/{lid}.json: no test file {src}")
            _write(os.path.join(d, "tests", tf), header + "\n" + open(src).read())
        if fr["tests"]:
            _write(os.path.join(d, "tests", "__init__.py"), header + "\n")
        for ex in fr["extra"]:
            src = os.path.join(ref, ex)
            if not ex.startswith(pkg + "/"):
                raise BuildError(f"manifest.d/{lid}.json: extra {ex} must be inside {pkg}/")
            dst = os.path.join(os.path.dirname(d), ex)
            if os.path.isdir(src):
                shutil.copytree(src, dst, dirs_exist_ok=True, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
            else:
                _write(dst, open(src).read())
    _write(os.path.join(starter_dir, "PARTS.md"), _parts_md(nn, stub, intro, todos_by_part))
    yml = os.path.join(ref, g["settings_file"])
    for d in (os.path.dirname(starter_dir), os.path.dirname(solution_dir)):
        dst = os.path.join(d, g["settings_file"])
        if os.path.exists(yml) and not os.path.exists(dst):
            _write(dst, open(yml).read())
    say(f"  wrote {os.path.relpath(starter_dir)} and {os.path.relpath(solution_dir)}: "
        f"{len(stub)} part(s), TODOs: {sum(len(v) for v in todos_by_part.values())}")
    if verify:
        _verify(lid, pkg, starter_dir, solution_dir, stubs_by_part, todos_by_part, fr["tests"], say)
    return {"parts": sorted(stub), "added": sorted(added), "todos": todos_by_part}


def _run(cmd, cwd):
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    env.pop("PYTHONPATH", None)
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=env, timeout=600)


def _verify(lid, pkg, starter_dir, solution_dir, stubs_by_part, todos_by_part, tests, say):
    starter_root = os.path.dirname(starter_dir)
    mods = sorted(stubs_by_part)
    code = "import importlib\nfor m in %r: importlib.import_module(%r + '.' + m)\n" % (mods, pkg)
    r = _run([sys.executable, "-B", "-c", code], starter_root)
    if r.returncode:
        raise BuildError(f"the starter does not import:\n{(r.stdout + r.stderr)[-1500:]}")
    for m, names in todos_by_part.items():               # every TODO of the starter is a stub
        text = open(os.path.join(starter_dir, *m.split(".")) + ".py").read()
        tree = ast.parse(text)
        defs = _defs_by_qualname(tree)
        for name in names:
            for fn in defs.get(name, []):
                seg = "\n".join(text.split("\n")[fn.lineno - 1:fn.end_lineno])   # with its comments
                if not any(mark in seg for mark in ('return None   # TODO', 'NotImplementedError("TODO')):
                    raise BuildError(f"{pkg}/{m}.py: TODO `{name}` is not a stub in the starter")
        sol = open(os.path.join(solution_dir, *m.split(".")) + ".py").read()
        if "return None   # TODO" in sol or 'NotImplementedError("TODO' in sol:
            raise BuildError(f"the reference {pkg}/{m}.py itself contains a TODO stub")
    if tests:
        r = _run([sys.executable, "-B", "-m", "pytest", "-q", "-p", "no:cacheprovider",
                  *[os.path.join(pkg, "tests", t) for t in tests]], os.path.dirname(solution_dir))
        if r.returncode:
            raise BuildError(f"the shipped tests fail on the solution:\n{(r.stdout + r.stderr)[-2500:]}")
        say("  pytest on the solution: " + (r.stdout.strip().splitlines() or ["?"])[-1])
    found = lite_lint.lint_paths([starter_dir, solution_dir])
    if found:
        raise BuildError("lite_lint:\n" + "\n".join(f"{os.path.relpath(f)}:{ln}: {m}" for f, ln, m in found))
    say(f"  verified {lid}: starter imports, TODOs are stubs, examples present, lint clean")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("lesson", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--parts", action="store_true", help="print part → introducing mission")
    ap.add_argument("--ref", default=REF, help="the reference folder (default solutions/_navera_lite)")
    ap.add_argument("--out", default=ACADEMY, help="root holding courses/ and solutions/ (default: this repo)")
    ap.add_argument("--no-verify", action="store_true")
    a = ap.parse_args(argv)
    try:
        g, frags = load_manifests(a.ref)
        if a.parts:
            for m, nn in sorted(parts_table(a.ref, g["package"]).items(), key=lambda x: (x[1], x[0])):
                print(f"{nn:02d}  {m}")
            return 0
        ids = sorted(frags) if a.all else [a.lesson] if a.lesson else []
        if a.all and not ids:
            print("no manifest fragment in manifest.d/: nothing to build")
            return 0
        if not ids:
            ap.error("give a mission id or --all")
        if a.out == ACADEMY:
            for lid in ids:
                if not os.path.isfile(os.path.join(ACADEMY, "courses", lid, "meta.json")):
                    raise BuildError(f"no mission courses/{lid}/ (use --out for a scratch build)")
        for lid in ids:
            print(f"{lid}:")
            build(lid, a.ref, a.out, verify=not a.no_verify)
    except BuildError as e:
        print(f"lite_build: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
