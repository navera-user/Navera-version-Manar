def test_lint_copy_check(tmp_path):
    base = tmp_path / "base"
    base.mkdir()
    body = "".join(f"    total = total + weight_{i} * value_{i}\n" for i in range(8))
    (base / "secret.py").write_text("def mix(values):\n    total = 0\n" + body + "    return total\n")
