GEO = '''\
"""navera_lite/geo.py — distances on the Earth. Part of NAVERA Lite, the course's teaching stack
(mission 06). Written for the course; it is not NAVERA code."""
import math

R_M = 6371000.0


# @part 06 todo 1
def haversine_m(lat1, lon1, lat2, lon2):
    """Great-circle distance between two points, in metres (sphere of radius R_M).

    Example:  haversine_m(0.0, 0.0, 0.0, 1.0)  ->  about 111194.9
    """
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R_M * math.asin(math.sqrt(a))


# @part 06
def is_finite_latlon(lat, lon):
    """True for a usable position (finite, in range, not (0, 0))."""
    return all(map(math.isfinite, (lat, lon))) and abs(lat) <= 90 and abs(lon) <= 180 and (lat, lon) != (0, 0)


# @part 07 todo 1
def tile_x(lon, z):
    """Fractional tile column of a longitude at zoom z.

    Example:  tile_x(0.0, 1)  ->  1.0
    """
    return (lon + 180.0) / 360.0 * 2 ** z


# @part 06
class Odometer:
    """Adds up the distance flown, point after point."""

    def __init__(self):
        self.total_m = 0.0
        self.last = None

    # @part 06 todo 2
    def add(self, lat, lon):
        """Add a point to the trip (nothing is returned).

        Example:  o = Odometer(); o.add(0.0, 0.0); o.add(0.0, 1.0); o.total_m  ->  about 111194.9
        """
        if self.last is not None:
            self.total_m += haversine_m(self.last[0], self.last[1], lat, lon)
        self.last = (lat, lon)

    # @part 08
    def reset(self):
        """Start a new trip."""
        self.total_m, self.last = 0.0, None


# @part 09
class Later:
    """Only from mission 09."""
'''

SPEED = '''\
"""navera_lite/speed.py — ground speed between two fixes. Part of NAVERA Lite (mission 06)."""
from navera_lite.geo import haversine_m


# @part 06 todo 3
def speed_mps(fix1, fix2):
    """Speed between two fixes (t_s, lat, lon), in m/s.

    Example:  speed_mps((0.0, 0.0, 0.0), (10.0, 0.0, 0.001))  ->  about 11.12
    """
    return haversine_m(fix1[1], fix1[2], fix2[1], fix2[2]) / (fix2[0] - fix1[0])
'''

