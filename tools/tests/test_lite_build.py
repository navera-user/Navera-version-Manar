    assert "self.rows = []" in s                              # __init__ has its own (given) tag
    assert 'raise NotImplementedError("TODO 4")' in s and "return None   # TODO" in s
    assert "geo" in (out / "courses/06-demo/files/navera_lite/__init__.py").read_text()
