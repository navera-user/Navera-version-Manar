#!/usr/bin/env bash
#
# navera_remote.sh — the public link: NAVERA's web page from anywhere, in any browser, with
# nothing to install for the viewer. A Tailscale Funnel https address reaches ONLY the access
# gate (navera_access_gate.py on 127.0.0.1), which asks for the box's remote key (in the link /
# the access card's QR code); from the internet the page is view-only by default.
#
#   navera_remote.sh --link     # print the public link (with the key) for the access card
#   sudo navera_remote.sh       # publish the gate through Tailscale Funnel (once; it persists)
#   sudo navera_remote.sh --stop
#
# Needs, once per box at provisioning: Tailscale installed and the box logged into IRIS's
# tailnet with Funnel allowed (sudo tailscale up --auth-key ...; see deploy/README.md §14), and
# internet for the box (Ethernet or a 4G USB modem: its Wi-Fi is the hotspot). Without internet
# the box works as always; only the public link is unreachable. Settings (/etc/navera/navera.env):
#   NAVERA_REMOTE            1 (default in product mode): publish; 0: no public link
#   NAVERA_REMOTE_KEY        the key in the link (generated by apply_product.sh)
#   NAVERA_REMOTE_PORT       the gate's local port (default 8190)
set -euo pipefail
PORT="${NAVERA_REMOTE_PORT:-8190}"
host() {
  tailscale status --json 2>/dev/null | python3 -c \
    'import json,sys; print(json.load(sys.stdin)["Self"]["DNSName"].rstrip("."))' 2>/dev/null
}
case "${1:-}" in
  --link)
    h=$(host) || true
    [ -n "$h" ] || { echo "Tailscale not logged in: no public link yet (deploy/README.md §14)" >&2; exit 1; }
    [ -n "${NAVERA_REMOTE_KEY:-}" ] || { echo "NAVERA_REMOTE_KEY empty" >&2; exit 1; }
    echo "https://$h/?k=$NAVERA_REMOTE_KEY" ;;
  --stop)
    tailscale funnel --https=443 off 2>/dev/null || true
    echo "public link off" ;;
  "")
    if [ "${NAVERA_REMOTE:-1}" = 0 ]; then echo "NAVERA_REMOTE=0: no public link"; exit 0; fi
    command -v tailscale >/dev/null || { echo "tailscale not installed: no public link" >&2; exit 1; }
    [ -n "$(host)" ] || { echo "Tailscale not logged in: no public link (deploy/README.md §14)" >&2; exit 1; }
    tailscale funnel --bg --https=443 "http://127.0.0.1:$PORT" >/dev/null
    echo "public link on: https://$(host)/ (the key is on the access card)" ;;
  -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//' ;;
  *) echo "unknown option: $1 (--help)" >&2; exit 2 ;;
esac
